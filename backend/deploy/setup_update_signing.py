#!/usr/bin/env python3
"""Generate Whitegram update signing keys and wire them into the client."""

from __future__ import annotations

import re
import sys
from pathlib import Path

try:
	from cryptography.hazmat.primitives.asymmetric import rsa
	from cryptography.hazmat.primitives import serialization
except ImportError:
	print("Install cryptography: pip install cryptography")
	sys.exit(1)

ROOT = Path(__file__).resolve().parents[2]
KEYS_DIR = Path(__file__).resolve().parent / "keys"
PRIVATE_PEM = KEYS_DIR / "whitegram_update_private.pem"
PUBLIC_PEM = KEYS_DIR / "whitegram_update_public.pem"
PACKER_PRIVATE = ROOT / "Telegram/SourceFiles/_other/packer_private.h"
CONFIG_H = ROOT / "Telegram/SourceFiles/config.h"
PACKER_CPP = ROOT / "Telegram/SourceFiles/_other/packer.cpp"
TARGET_FILE = ROOT / "Telegram/build/target"


def pem_to_c_string(pem: bytes) -> str:
	text = pem.decode("ascii").strip()
	lines = text.split("\n")
	body = "\\n".join(lines)
	return f'"{body}\\n"'


def generate_keys() -> tuple[bytes, bytes]:
	private_key = rsa.generate_private_key(
		public_exponent=65537,
		key_size=1024,
	)
	private_pem = private_key.private_bytes(
		encoding=serialization.Encoding.PEM,
		format=serialization.PrivateFormat.TraditionalOpenSSL,
		encryption_algorithm=serialization.NoEncryption(),
	)
	public_pem = private_key.public_key().public_bytes(
		encoding=serialization.Encoding.PEM,
		format=serialization.PublicFormat.PKCS1,
	)
	return private_pem, public_pem


def load_or_create_keys() -> tuple[bytes, bytes]:
	KEYS_DIR.mkdir(parents=True, exist_ok=True)
	if PRIVATE_PEM.exists() and PUBLIC_PEM.exists():
		return PRIVATE_PEM.read_bytes(), PUBLIC_PEM.read_bytes()
	private_pem, public_pem = generate_keys()
	PRIVATE_PEM.write_bytes(private_pem)
	PUBLIC_PEM.write_bytes(public_pem)
	print(f"Created {PRIVATE_PEM}")
	print(f"Created {PUBLIC_PEM}")
	return private_pem, public_pem


def write_packer_private(private_pem: bytes) -> None:
	public_pem = PUBLIC_PEM.read_bytes()
	private_c = pem_to_c_string(private_pem)
	public_c = pem_to_c_string(public_pem)
	content = f"""// Generated by backend/deploy/setup_update_signing.py
// Do not commit this file.

const char *PrivateKey = {private_c};

const char *PrivateBetaKey = {private_c};
"""
	PACKER_PRIVATE.write_text(content, encoding="utf-8", newline="\n")
	print(f"Wrote {PACKER_PRIVATE}")


def format_public_key_c(name: str, public_pem: bytes, *, static_decl: bool) -> str:
	lines = public_pem.decode("ascii").strip().split("\n")
	escaped = []
	for index, line in enumerate(lines):
		suffix = "\\n\\" if index < len(lines) - 1 else "\\"
		escaped.append(f"{line}{suffix}")
	decl = "static const char *" if static_decl else "const char *"
	inner = "\n".join(escaped)
	return f'{decl}{name} = "\\\n{inner}\n";'


def replace_public_key(path: Path, name: str, public_pem: bytes, *, static_decl: bool) -> None:
	text = path.read_text(encoding="utf-8")
	replacement = format_public_key_c(name, public_pem, static_decl=static_decl)
	pattern = re.compile(
		(r"static const char \*" if static_decl else r"const char \*")
		+ re.escape(name)
		+ r' = "\\.*?";',
		re.DOTALL,
	)
	new_text, count = pattern.subn(replacement, text, count=1)
	if count != 1:
		raise RuntimeError(f"Could not update {name} in {path}")
	path.write_text(new_text, encoding="utf-8", newline="\n")
	print(f"Updated {name} in {path.name}")


def ensure_target() -> None:
	TARGET_FILE.write_text("win64\n", encoding="utf-8", newline="\n")
	print(f"Wrote {TARGET_FILE}")


def main() -> int:
	private_pem, public_pem = load_or_create_keys()
	write_packer_private(private_pem)
	replace_public_key(CONFIG_H, "UpdatesPublicKey", public_pem, static_decl=True)
	replace_public_key(CONFIG_H, "UpdatesPublicBetaKey", public_pem, static_decl=True)
	replace_public_key(PACKER_CPP, "PublicKey", public_pem, static_decl=False)
	replace_public_key(PACKER_CPP, "PublicBetaKey", public_pem, static_decl=False)
	ensure_target()
	print("")
	print("Done. Next steps:")
	print("  1. Reconfigure CMake (Telegram/build/target is now win64)")
	print("  2. Build Release: cmake --build out --config Release --target Telegram")
	print("  3. Pack update: Telegram\\build\\whitegram_pack_update.bat")
	print("  4. Publish: python backend/deploy/push_update.py")
	return 0


if __name__ == "__main__":
	sys.exit(main())
